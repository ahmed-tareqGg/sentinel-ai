import { useState, useEffect } from 'react';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Badge } from '@/components/ui/badge';
import { Brain, FileText, Loader2, Download, Clock } from 'lucide-react';
import { supabase } from '@/integrations/backend/client';
import { useAuth } from '@/hooks/useAuth';
import { toast } from 'sonner';
import { logUserAction } from '@/lib/auditLogger';
import jsPDF from 'jspdf';

interface Report {
  id: string;
  title: string;
  content: string;
  format: string;
  generated_by_email: string | null;
  generated_by_role: string | null;
  ai_model: string | null;
  created_at: string;
}

interface AIReportGeneratorProps {
  incidentId: string;
  incident: any;
}

export function AIReportGenerator({ incidentId, incident }: AIReportGeneratorProps) {
  const { user, profile, role } = useAuth();
  const [reports, setReports] = useState<Report[]>([]);
  const [generating, setGenerating] = useState(false);
  const [loading, setLoading] = useState(true);
  const [activeReport, setActiveReport] = useState<string | null>(null);

  useEffect(() => {
    fetchReports();
  }, [incidentId]);

  const fetchReports = async () => {
    const { data, error } = await supabase
      .from('incident_reports')
      .select('*')
      .eq('incident_id', incidentId)
      .order('created_at', { ascending: false });

    if (error) console.error('Error fetching reports:', error);
    else setReports(data || []);
    setLoading(false);
  };

  const generateReport = async () => {
    setGenerating(true);

    try {
      // Fetch IOCs, evidence, notes, timeline
      const [iocRes, evidenceRes, notesRes, timelineRes] = await Promise.all([
        supabase.from('incident_iocs').select('*').eq('incident_id', incidentId),
        supabase.from('incident_evidence').select('*').eq('incident_id', incidentId),
        supabase.from('analyst_notes').select('*').eq('incident_id', incidentId),
        supabase.from('incident_timeline').select('*').eq('incident_id', incidentId).order('timestamp', { ascending: true }),
      ]);

      const roleLabels: Record<string, string> = {
        soc_tier_1: 'SOC Tier 1 Analyst',
        soc_tier_2: 'SOC Tier 2 Analyst',
        soc_tier_3: 'SOC Tier 3 Senior Analyst',
        soc_manager: 'SOC Manager',
        admin: 'Administrator',
        ciso: 'CISO',
        grc_engineer: 'GRC Engineer',
      };

      const { data, error } = await supabase.functions.invoke('generate-investigation-report', {
        body: {
          incident,
          iocs: iocRes.data || [],
          evidence: evidenceRes.data || [],
          notes: notesRes.data || [],
          timeline: timelineRes.data || [],
          investigator: {
            name: profile?.full_name || profile?.email || 'Analyst',
            role: roleLabels[role || ''] || role || 'SOC Analyst',
          },
        },
      });

      if (error) throw error;

      const reportContent = data.report;

      // Save report to DB
      const { error: saveErr } = await supabase.from('incident_reports').insert({
        incident_id: incidentId,
        report_type: 'investigation',
        title: `Investigation Report — ${incident.incident_number}`,
        content: reportContent,
        format: 'markdown',
        generated_by: user?.id,
        generated_by_email: profile?.email,
        generated_by_role: role,
        ai_model: 'gemini-2.5-flash',
      });

      if (saveErr) throw saveErr;

      await supabase.from('incident_timeline').insert({
        incident_id: incidentId,
        stage: 'AI Investigation Report Generated',
        details: `Generated by ${profile?.email} (${roleLabels[role || ''] || role})`,
      });

      await logUserAction('generate_investigation_report', 'incident_report', incidentId, 'success', {
        incident_number: incident.incident_number,
      });

      toast.success('Investigation report generated');
      fetchReports();
    } catch (err) {
      console.error('Report generation failed:', err);
      toast.error('Failed to generate report');
    } finally {
      setGenerating(false);
    }
  };

  const exportPDF = (report: Report) => {
    const pdf = new jsPDF();
    const pageWidth = pdf.internal.pageSize.getWidth();
    let y = 20;

    pdf.setFontSize(18);
    pdf.setTextColor(0, 100, 200);
    pdf.text('SOCMind INVESTIGATION REPORT', pageWidth / 2, y, { align: 'center' });
    y += 12;

    pdf.setDrawColor(0, 100, 200);
    pdf.line(20, y, pageWidth - 20, y);
    y += 10;

    pdf.setFontSize(10);
    pdf.setTextColor(100, 100, 100);
    pdf.text(`Generated: ${new Date(report.created_at).toLocaleString()}`, 20, y);
    pdf.text(`By: ${report.generated_by_email}`, 20, y + 5);
    y += 15;

    pdf.setFontSize(10);
    pdf.setTextColor(0, 0, 0);
    const lines = pdf.splitTextToSize(report.content.replace(/[#*`]/g, ''), pageWidth - 40);
    
    for (const line of lines) {
      if (y > pdf.internal.pageSize.getHeight() - 20) {
        pdf.addPage();
        y = 20;
      }
      pdf.text(line, 20, y);
      y += 5;
    }

    pdf.save(`Investigation_Report_${incident.incident_number}.pdf`);
    toast.success('PDF exported');
  };

  return (
    <Card>
      <CardHeader className="pb-3">
        <CardTitle className="text-base flex items-center gap-2">
          <Brain className="h-4 w-4 text-primary" />
          AI Investigation Reports
          <Badge variant="secondary" className="ml-auto">{reports.length}</Badge>
          <Button onClick={generateReport} disabled={generating} size="sm" className="bg-primary">
            {generating ? (
              <Loader2 className="h-4 w-4 mr-1 animate-spin" />
            ) : (
              <Brain className="h-4 w-4 mr-1" />
            )}
            {generating ? 'Generating...' : 'Generate Report'}
          </Button>
        </CardTitle>
      </CardHeader>
      <CardContent>
        {loading ? (
          <div className="flex justify-center py-6">
            <Loader2 className="h-6 w-6 animate-spin text-muted-foreground" />
          </div>
        ) : reports.length === 0 ? (
          <div className="text-center py-8">
            <Brain className="h-10 w-10 text-muted-foreground mx-auto mb-3" />
            <p className="text-sm text-muted-foreground">No reports generated yet</p>
            <p className="text-xs text-muted-foreground mt-1">Add IOCs, evidence, and notes first for a richer report</p>
          </div>
        ) : (
          <div className="space-y-3">
            {reports.map((report) => (
              <div key={report.id} className="space-y-2">
                <div
                  className="flex items-center justify-between p-3 rounded-lg border border-border bg-secondary/20 cursor-pointer hover:bg-secondary/40 transition-colors"
                  onClick={() => setActiveReport(activeReport === report.id ? null : report.id)}
                >
                  <div className="flex items-center gap-3 min-w-0">
                    <FileText className="h-4 w-4 text-primary shrink-0" />
                    <div className="min-w-0">
                      <p className="text-sm font-medium truncate">{report.title}</p>
                      <div className="flex items-center gap-2 text-xs text-muted-foreground">
                        <Clock className="h-3 w-3" />
                        <span>{new Date(report.created_at).toLocaleString()}</span>
                        <span>by {report.generated_by_email}</span>
                        <Badge variant="outline" className="text-[10px]">{report.generated_by_role}</Badge>
                      </div>
                    </div>
                  </div>
                  <Button variant="ghost" size="sm" onClick={(e) => { e.stopPropagation(); exportPDF(report); }}>
                    <Download className="h-4 w-4" />
                  </Button>
                </div>
                {activeReport === report.id && (
                  <div className="rounded-lg border border-border bg-card p-4 ml-4">
                    <div className="prose prose-sm dark:prose-invert max-w-none text-sm text-muted-foreground whitespace-pre-wrap leading-relaxed">
                      {report.content}
                    </div>
                  </div>
                )}
              </div>
            ))}
          </div>
        )}
      </CardContent>
    </Card>
  );
}
